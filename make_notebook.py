    "\n",
    "This is the **most important correctness step** in the project. If you naively join news to the calendar day it was published, you allow **information leakage**: an article published at 20:00 IST cannot possibly affect the *same* session's return, because that session already closed at 15:30 IST.\n",
    "\n",
    "### The 15:45 IST cutoff rule\n",
    "\n",
    "Each trading session is assigned a **cutoff time of 15:45 IST** — 15 minutes after the official NSE close of 15:30, allowing for late closing-price updates.\n",
    "\n",
    "| Article publication time | Assigned to session |\n",
    "| :--- | :--- |\n",
    "| 09:15 IST Monday | Monday (pre-market, influences Monday) |\n",
    "| 11:00 IST Monday | Monday |\n",
